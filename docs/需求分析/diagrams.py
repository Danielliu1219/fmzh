def encode_puml(uml):
    """PlantUML 官方编码：raw deflate + 自定义 base64 字母表（0-9 A-Z a-z - _，数字在前）。
    标准 base64 会被服务器错误解码导致中文乱码，必须用此官方口径。"""
    data = zlib.compress(uml.encode('utf-8'), 9)[2:-4]
    out = []
    for i in range(0, len(data), 3):
        b1, b2, b3 = data[i], data[i + 1] if i + 1 < len(data) else 0, data[i + 2] if i + 2 < len(data) else 0
        c1 = b1 >> 2
        c2 = ((b1 & 0x3) << 4) | (b2 >> 4)
        c3 = ((b2 & 0xF) << 2) | (b3 >> 6)
        c4 = b3 & 0x3F
        for c in (c1, c2, c3, c4):
            if c < 10:
                out.append(chr(48 + c))
            elif c < 36:
                out.append(chr(65 + c - 10))
            elif c < 62:
                out.append(chr(97 + c - 36))
            elif c == 62:
                out.append('-')
            else:
                out.append('_')
    return ''.join(out)


def render(name, uml):
    if 'skinparam dpi' not in uml:
        uml = uml.replace('@startuml', '@startuml\nskinparam dpi 200', 1)
    url = 'https://www.plantuml.com/plantuml/png/' + encode_puml(uml)
    for attempt in range(3):
        try:
            req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
            resp = urllib.request.urlopen(req, timeout=30)
            data = resp.read()
            if data[:4] != b'\x89PNG':
                raise ValueError('not a PNG')
            with open(os.path.join(FIG, name + '.png'), 'wb') as f:
                f.write(data)
            return True
        except Exception as e:
            if attempt == 2:
                print('FAILED %s: %s' % (name, str(e)[:120]))
                return False
            time.sleep(2)


