def act(nodes):
    """由结构化节点列表生成活动图 PlantUML 源码"""
    lines = ['@startuml', 'skinparam defaultFontName "Noto Sans CJK SC"', 'start']
    for n in nodes:
        k = n[0]
        if k == 'a':
            lines.append(':%s;' % n[1])
        elif k == 'if':
            yes = n[2] if len(n) > 2 else '是'
            no = n[3] if len(n) > 3 else '否'
            lines.append('if (%s) then (%s)' % (n[1], yes))
        elif k == 'else':
            label = n[1] if len(n) > 1 else '否'
            lines.append('else (%s)' % label)
        elif k == 'endif':
            lines.append('endif')
        elif k == 'stop':
            lines.append('stop')
        elif k == 'end':
            lines.append('end')
    lines.append('@enduml')
    return '\n'.join(lines)


def uc_diagram(actors, usecases, links, title=''):
    """生成用例图源码。actors: [(别名, 名称, 构造型或None)]；usecases: [(别名, 名称)]；links: [(from, to, 关系或None)]"""
    lines = ['@startuml', 'skinparam defaultFontName "Noto Sans CJK SC"',
             'left to right direction']
    for alias, name, stereo in actors:
        if stereo:
            lines.append('actor "%s" as %s <<%s>>' % (name, alias, stereo))
        else:
            lines.append('actor "%s" as %s' % (name, alias))
    lines.append('rectangle "%s" {' % title if title else '')
    if title:
        for alias, name in usecases:
            lines.append('  usecase "%s" as %s' % (name, alias))
        lines.append('}')
    else:
        for alias, name in usecases:
            lines.append('usecase "%s" as %s' % (name, alias))
    for frm, to, rel in links:
        if rel:
            lines.append('%s ..> %s : <<%s>>' % (frm, to, rel))
        else:
            lines.append('%s --> %s' % (frm, to))
    lines.append('@enduml')
    return '\n'.join(lines)


